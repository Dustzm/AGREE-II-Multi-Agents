class IterativeEvaluator:
    """
    迭代评价器 - 遍历 chunks，累积证据，动态评分
    
    流程：
    1. 按文章原始顺序遍历 chunks
    2. 对每个 chunk 调用 LLM 提取证据
    3. 累积证据后调用 LLM 动态评分
    4. 满分 (7分) 时早停
    5. 最终生成完整 CoT 报告
    """
    
    def __init__(
        self,
        task_id: str,
        skill_id: str,
        lang: str = "en",
        cancellation_token: CancellationToken | None = None,
        analysis_engine: str | None = None,
    ):
        """
        初始化评价器
        
        Args:
            task_id: 任务 ID
            skill_id: 条目 ID (如 "item_7")
            lang: 提示词语言 (默认 en)
            analysis_engine: 本任务使用的评价引擎；为空时沿用全局配置
        """
        self.task_id = task_id
        self.skill_id = skill_id
        self.lang = lang
        self.cancellation_token = cancellation_token
        
        # 累积状态
        self.evidence_cache: List[str] = []      # 累积的证据文本
        self.evidence_chunk_map: List[str] = []  # 每条证据对应的 chunk_id（与 evidence_cache 一一对应）
        self.evidence_sources: List[str] = []    # 所有处理过的 chunk_id 列表
        self.current_score: int = 1              # 当前评分
        self._chunk_lookup: Dict[str, SemanticChunk] = {}
        self._rule_engine_payload: Dict[str, Any] | None = None
        self._hybrid_route_decision: HybridRouteDecision | None = None
        
        # 加载配置
        self.skill_config = load_skill_config(skill_id, check_enabled=True, lang=lang)
        self.domain_id = self.skill_config.get("domain", 1)
        
        # LLM 配置
        settings = get_settings()
        self.analysis_engine = analysis_engine or settings.app.analysis_engine
        if self.analysis_engine not in {"llm", "rule", "hybrid"}:
            raise ValueError(f"不支持的评价引擎: {self.analysis_engine}")
        llm_settings = current_llm_settings()
        self.gateway = LLMGateway.from_settings(llm_settings)
        self.budget = self.gateway.budget
        self.is_vision_model = llm_settings.is_vision_model
        self.recovery = RecoveryBudget()
        self._output_tokens = {
            stage: self.gateway.output_limit(tokens)
            for stage, tokens in {"evidence_extraction": 8192, "dynamic_scoring": 12000, "item_report": 16384}.items()
        }
        self._llm_call_counts: Counter[str] = Counter()
        self.failed_stage: str | None = None
        
        logger.info(
            "IterativeEvaluator 初始化: task=%s, skill=%s, domain=%s, analysis_engine=%s",
            task_id,
            skill_id,
            self.domain_id,
            self.analysis_engine,
        )

    def _with_rule_engine_payload(self, result: Dict[str, Any]) -> Dict[str, Any]:
        """Attach optional Rule and Dynamic-Hybrid execution details."""
        if self._rule_engine_payload is not None:
            result["rule_engine"] = self._rule_engine_payload
        if self._hybrid_route_decision is not None:
            result["hybrid_router"] = self._hybrid_route_decision.as_payload()
        return result

    def _retry_llm_call(self, stage: str, call, retryable=is_retryable_llm_error):
        """整个条目共用三次额外机会，只重发当前失败调用。"""
        def attempt():
            self._llm_call_counts[stage] += 1
            return call()

        def grow_truncated_output(error):
            # 截断时放大输出上限再重试；已到上限则直接失败。
            if isinstance(error, TruncatedModelOutput):
                increased = self.gateway.output_limit(self._output_tokens[stage] * 2)
                if increased == self._output_tokens[stage]:
                    raise error
                self._output_tokens[stage] = increased
            logger.warning("条目模型调用重试: task=%s item=%s stage=%s error=%s", self.task_id, self.skill_id, stage, type(error).__name__)

        try:
            return self.recovery.run(attempt, check_cancelled=self._raise_if_cancelled,
                                     retryable=retryable, before_retry=grow_truncated_output)
        except CancellationRequested:
            raise
        except Exception as error:
            self.failed_stage = stage
            tag_stage(error, stage)
            raise

    def _scoring_table(self) -> str:
        return "\n".join(
            f"| {sp['range']} | {sp.get('condition', sp.get('condition_zh', ''))} |"
            for sp in self.skill_config.get("scoring_principle", [])
        )

    def _raise_if_cancelled(self) -> None:
        if self.cancellation_token is not None:
            self.cancellation_token.raise_if_cancelled()

    @property
    def _is_item17(self) -> bool:
        return self.skill_id == "item_17"

    def _item17_packer(self) -> Item17EvidencePacker:
        return Item17EvidencePacker(
            budget=self.budget, evidence=self.evidence_cache,
            chunk_ids=self.evidence_chunk_map, chunk_lookup=self._chunk_lookup,
        )

    def evaluate(self) -> Dict[str, Any]:
        """
        执行迭代评价
        
        Returns:
            评价结果字典
        """
        # 1. 加载证据池
        self._raise_if_cancelled()
        paths = get_task_paths(self.task_id)
        if not paths:
            return self._error_result(f"任务不存在: {self.task_id}")
        
        prep_dir = paths["prep_dir"]
        
        try:
            pool = EvidencePool.load(prep_dir)
        except FileNotFoundError as e:
            return self._error_result(f"证据池加载失败: {e}")
        self._chunk_lookup = {chunk.chunk_id: chunk for chunk in pool.chunks}

        settings = get_settings()
        use_rule_engine = is_rule_engine_enabled_for_item(
            self.skill_id,
            analysis_engine=self.analysis_engine,
        )
        if self.analysis_engine == "hybrid":
            try:
                self._hybrid_route_decision = select_appraisal_path(
                    pool,
                    self.skill_id,
                    self.domain_id,
                )
            except Exception as exc:
                logger.exception(
                    "Dynamic-Hybrid Router 执行失败: task=%s, item=%s",
                    self.task_id,
                    self.skill_id,
                )
                return self._error_result(f"Dynamic-Hybrid Router 执行失败: {exc}")
            use_rule_engine = self._hybrid_route_decision.selected_path == "rule"
            logger.info(
                "Dynamic-Hybrid Router 决策: task=%s, item=%s, path=%s, confidence=%.6f",
                self.task_id,
                self.skill_id,
                self._hybrid_route_decision.selected_path,
                self._hybrid_route_decision.confidence,
            )

        if use_rule_engine:
            policy = RuleFailurePolicy.from_settings(settings)
            logger.info(
                "规则引擎路径命中: task=%s, item=%s, fallback_policy=%s",
                self.task_id,
                self.skill_id,
                policy.mode,
            )
            try:
                result = RuleAppraiserAdapter.from_evaluator(self).evaluate(pool.chunks)
                return self._with_rule_engine_payload(result)
            except CancellationRequested:
                raise
            except Exception as exc:
                if not getattr(exc, "appraisal_stage", None):
                    exc.appraisal_stage = f"rule_engine:{self.skill_id}"
                decision = policy.decide(self.skill_id, exc)
                payload_meta = {
                    "degraded": decision.degraded,
                    "failure_kind": decision.kind.value,
                    "fallback_reason": decision.reason,
                }
                if decision.fatal:
                    logger.exception(
                        "规则引擎评价失败，按策略不回退: item=%s kind=%s reason=%s",
                        self.skill_id,
                        decision.kind.value,
                        decision.reason,
                    )
                    self._rule_engine_payload = build_rule_engine_error_payload(
                        self.skill_id,
                        str(exc),
                        fallback_used=False,
                        analysis_engine=self.analysis_engine,
                        **payload_meta,
                    )
                    raise

                logger.warning(
                    "规则引擎评价失败，降级回退到 LLM appraiser: item=%s kind=%s reason=%s",
                    self.skill_id,
                    decision.kind.value,
                    decision.reason,
                    exc_info=True,
                )
                self._rule_engine_payload = build_rule_engine_error_payload(
                    self.skill_id,
                    str(exc),
                    fallback_used=True,
                    analysis_engine=self.analysis_engine,
                    **payload_meta,
                )
                if self._hybrid_route_decision is not None:
                    self._hybrid_route_decision = (
                        self._hybrid_route_decision.with_executed_path("llm")
                    )
                # 规则路径可能已耗尽本条目的恢复配额（BUDGET_EXCEEDED 正是降级原因之一）；
                # 回退路径换一份新配额，否则一次传输抖动就会让降级评价直接失败。
                self.recovery = RecoveryBudget()
        else:
            logger.info("使用 LLM appraiser 路径: item=%s", self.skill_id)
        
        # 2. 创建迭代器
        iterator = EvidenceIterator(pool.chunks, self.domain_id)
        
        if len(iterator) == 0:
            logger.warning(f"领域 {self.domain_id} 无相关 chunks，自动评分为 1")
            return self._no_evidence_result()
        
        logger.info(f"开始迭代评价: {len(iterator)} 个 chunks")
        
        # 3. 迭代遍历 (使用 batch 加速)
        batch_size = 5
        iterator_list = list(iterator)
        
        for i in range(0, len(iterator_list), batch_size):
            self._raise_if_cancelled()
            batch_chunks = iterator_list[i:i+batch_size]
            logger.info(f"处理 batch {i//batch_size + 1}/{(len(iterator_list)+batch_size-1)//batch_size}: 包含 {len(batch_chunks)} 个 chunks")
            
            # 3.1 提取证据 (Batch) - 返回 (evidence_texts, chunk_ids)
            new_evidence, new_chunk_ids = self._extract_with_budget(batch_chunks)
            
            if new_evidence:
                known = set(zip(self.evidence_chunk_map, self.evidence_cache))
                for source, evidence in zip(new_chunk_ids, new_evidence):
                    pair = (strip_surrogates(source), strip_surrogates(evidence))
                    if pair not in known:
                        self.evidence_chunk_map.append(pair[0])
                        self.evidence_cache.append(pair[1])
                        known.add(pair)
                for chunk in batch_chunks:
                    self.evidence_sources.append(strip_surrogates(chunk.chunk_id))
                logger.info(f"Batch 提取到 {len(new_evidence)} 条证据")
            
            # 3.2 动态评分 (仅在有新证据时)
            if new_evidence:
                self.current_score = self._retry_llm_call("dynamic_scoring", self._score_current)
                logger.info(f"当前评分: {self.current_score}")
            
            # 3.3 早停检查
            if self.current_score == 7:
                logger.info(f"达到满分 7 分，提前结束")
                break
        
        # 4. 生成最终报告
        try:
            return self._retry_llm_call("item_report", self._synthesize_report)
        except InvalidModelJSON as error:
            # 报告的结构化推理属于展示层内容；模型多次输出仍不符合结构时降级为
            # 文本说明，避免已经算出的评分与证据随整条评价一起失败。
            logger.warning(
                "最终报告结构化推理无效，降级为文本说明: task=%s item=%s error=%s",
                self.task_id,
                self.skill_id,
                error,
            )
            return self._degraded_report(str(error))
    
    def _extract_with_budget(self, chunks):
        """Split at source boundaries; only an oversized single chunk is subdivided."""
        def extract(batch):
            # 截断说明输入过多，交给拆分处理而不是放大输出重试。
            return self._retry_llm_call(
                "evidence_extraction", lambda: self._extract_evidence_batch(batch),
                retryable=lambda error: is_retryable_llm_error(error) and not isinstance(error, TruncatedModelOutput),
            )

        def merge(parts):
            return ([text for _, (texts, _) in parts for text in texts],
                    [source for _, (_, sources) in parts for source in sources])

        return split_on_overflow(list(chunks), extract, merge, client=self, split_single=split_chunk)

    def _extract_evidence_batch(self, chunks: List[SemanticChunk]) -> tuple[List[str], List[str]]:
        """
        从 batch chunks 提取与评价标准相关的证据
        
        Args:
            chunks: 语义块列表
        
        Returns:
            (evidence_texts, chunk_ids) 元组：证据文本列表和对应的 chunk_id 列表
        """
        # 记录处理的 chunk 内容
        self._raise_if_cancelled()
        for c in chunks:
            logger.info(f"Evaluating Chunk: {c.title}")

        # 拼接 chunk 内容（带 chunk_id 标记，便于 LLM 识别来源）
        combined_content = []
        for c in chunks:
            chunk_text = f"[{strip_surrogates(c.chunk_id)}] ## {strip_surrogates(c.title)}\n{strip_surrogates(c.content)}"
            
            # 条目17：注入格式元数据供 LLM 评价推荐意见呈现方式
            if self.skill_id == "item_17" and getattr(c, "format_hints", None):
                format_desc = c.format_hints.get("format_description", "")
                if format_desc:
                    chunk_text += f"\n\n{strip_surrogates(format_desc)}"
            
            combined_content.append(chunk_text)
        
        full_text = "\n\n".join(combined_content)


        prompt = render_extraction_prompt(
            item_id=self.skill_id,
            title=self.skill_config.get("title", ""),
            scoring_table=self._scoring_table(),
            chunk_content=full_text,
            special_instruction=self.skill_config.get("special_rules", ""),
        )
        prompt = strip_surrogates(prompt)
        
        try:
            self._raise_if_cancelled()
            data = self.gateway.complete(
                f"appraiser:{self.skill_id}:evidence_extraction",
                [
                    {"role": "system", "content": "You are a strict extraction system. Output JSON only."},
                    {"role": "user", "content": prompt},
                ],
                max_tokens=self._output_tokens["evidence_extraction"],
            ).json()

            # 解析 JSON（新格式：包含 chunk_id）
            evidence_texts: List[str] = []
            chunk_ids: List[str] = []
            
            if not isinstance(data.get("evidence"), list):
                raise InvalidModelJSON("证据提取结果缺少 evidence 数组")
            evidence_list = data["evidence"]
            
            # 解析新格式 [{chunk_id, evidence}]
            for item in evidence_list:
                if isinstance(item, dict):
                    if not isinstance(item.get("evidence"), str):
                        raise InvalidModelJSON("证据提取条目缺少 evidence 文本")
                    # 新格式：{"chunk_id": "xxx", "evidence": "text"}
                    chunk_id = item.get("chunk_id")
                    if chunk_id not in {chunk.chunk_id for chunk in chunks}:
                        raise InvalidModelJSON("证据引用了未知 chunk_id")
                    evidence_text = item.get("evidence", "")
                    if evidence_text:
                        evidence_texts.append(strip_surrogates(str(evidence_text)))
                        chunk_ids.append(strip_surrogates(str(chunk_id)))
                elif isinstance(item, str) and item and len(chunks) == 1:
                    # 兼容旧格式：纯字符串数组（回退到第一个 chunk）
                    evidence_texts.append(strip_surrogates(str(item)))
                    chunk_ids.append(strip_surrogates(chunks[0].chunk_id if chunks else "unknown"))
                else:
                    raise InvalidModelJSON("证据提取结果包含无效条目")

            return evidence_texts, chunk_ids
            
        except CancellationRequested:
            raise
        except Exception as e:
            logger.exception("Batch 证据提取失败: %s", e)
            raise

    
    def _score_current(self) -> int:
        """
        根据当前累积证据评分
        
        Returns:
            当前评分 (1-7)
        """
        scoring_table = self._scoring_table()
        
        try:
            self._raise_if_cancelled()
            if self._is_item17:
                # 预算无法容纳完整证据属于确定性失败（ContextBudgetExceeded），重试无益。
                messages = self._item17_packer().scoring_request(
                    lambda evidence, chunk_ids: strip_surrogates(render_scoring_prompt(
                        item_id=self.skill_id,
                        title=self.skill_config.get("title", ""),
                        shots=self.skill_config.get("shots", []),
                        evidence_cache=evidence,
                        scoring_table=scoring_table,
                        n_sources=len(set(chunk_ids)),
                        special_instruction=self.skill_config.get("special_rules", ""),
                    )),
                    vision_prompt=self.skill_config.get("vision_prompt", "Please judge based on the provided images."),
                    output_tokens=self._output_tokens["dynamic_scoring"],
                    is_vision_model=self.is_vision_model,
                    task_id=self.task_id,
                ).messages
            else:
                prompt = render_scoring_prompt(
                    item_id=self.skill_id,
                    title=self.skill_config.get("title", ""),
                    shots=self.skill_config.get("shots", []),
                    evidence_cache=self.evidence_cache,
                    scoring_table=scoring_table,
                    n_sources=len(self.evidence_sources),
                    special_instruction=self.skill_config.get("special_rules", ""),
                )
                api_prompt = strip_surrogates(prompt)
                messages = [
                    {"role": "system", "content": "You are a scoring assistant. Output JSON only."},
                    {"role": "user", "content": api_prompt},
                ]

            data = self.gateway.complete(
                f"appraiser:{self.skill_id}:dynamic_scoring",
                messages,
                max_tokens=self._output_tokens["dynamic_scoring"],
            ).json()
            return self._score_from_json_data(data)
            
        except CancellationRequested:
            raise
        except Exception as e:
            logger.exception("评分失败: %s", e)
            raise

    def _score_from_json_data(self, data: Dict[str, Any]) -> int:
        """Extract and validate a 1-7 score from parsed scoring JSON."""
        if "score" not in data:
            raise InvalidModelJSON("动态评分结果缺少 score")
        score = data["score"]

        # 处理可能的范围格式如 "3-4"
        if isinstance(score, str):
            try:
                score = int(score.split("-")[-1].strip())
            except ValueError as error:
                raise InvalidModelJSON(f"动态评分结果无效: {score}") from error

        if isinstance(score, int) and not isinstance(score, bool) and 1 <= score <= 7:
            logger.info(f"从 JSON 提取到评分: {score}")
            return score

        raise InvalidModelJSON(f"动态评分结果超出 1-7 范围: {score}")

    def _synthesize_report(self) -> Dict[str, Any]:
        """
        综合所有证据生成最终报告
        
        Returns:
            完整评价结果
        """
        scoring_table = self._scoring_table()
        
        report_evidence = self.evidence_cache
        if self._is_item17:
            selection = self._item17_packer().report_selection(
                lambda evidence, chunk_ids: strip_surrogates(render_final_report_prompt(
                    item_id=self.skill_id,
                    domain_name=self.skill_config.get("domain_name", ""),
                    title=self.skill_config.get("title", ""),
                    shots=self.skill_config.get("shots", []),
                    scoring_table=scoring_table,
                    evidence_cache=evidence,
                    evidence_chunk_map=chunk_ids,
                    final_score=self.current_score,
                )),
                output_tokens=self._output_tokens["item_report"],
            )
            prompt = selection.prompt
            report_evidence = selection.evidence
        else:
            prompt = render_final_report_prompt(
                item_id=self.skill_id,
                domain_name=self.skill_config.get("domain_name", ""),
                title=self.skill_config.get("title", ""),
                shots=self.skill_config.get("shots", []),
                scoring_table=scoring_table,
                evidence_cache=self.evidence_cache,
                evidence_chunk_map=self.evidence_chunk_map,  # 使用精确映射
                final_score=self.current_score,
            )
            prompt = strip_surrogates(prompt)

        self._raise_if_cancelled()
        # 最终报告只基于已抽取证据生成，避免重复注入图片导致上下文膨胀。
        # 使用简单 json_object 避免 SGLang xgrammar 兼容性问题。
        cot = sanitize_unicode(self.gateway.complete(
            f"appraiser:{self.skill_id}:final_report",
            [
                {"role": "system", "content": "You are an evaluation report generator. Output valid JSON matching the required schema."},
                {"role": "user", "content": prompt},
            ],
            max_tokens=self._output_tokens["item_report"],
        ).json())
        if not isinstance(cot, dict):
            raise InvalidModelJSON("条目报告 JSON 结构无效")

        # 兼容既有结构化推理和非空文本；空推理必须重试当前报告调用。
        step3_reasoning = coerce_step3_reasoning(cot.get("step3_reasoning"))

        step1_locate = cot.get("step1_locate")
        if (not isinstance(step1_locate, str) or not step1_locate.strip()) and self.evidence_sources:
            step1_locate = self._text("locate_sources", sources=", ".join(self.evidence_sources))
        if not isinstance(step1_locate, str) or not step1_locate.strip():
            raise InvalidModelJSON("条目报告缺少有效的证据位置")

        return self._success_result(step1_locate, report_evidence, step3_reasoning)

    def _degraded_report(self, reason: str) -> Dict[str, Any]:
        """Fallback report when the model cannot produce structured reasoning.

        The item score and evidence are already available at this point; only the
        narrative reasoning is missing, so keep the item successful and mark the
        report as degraded instead of failing the whole appraisal item.
        """
        evidence_preview = "; ".join(
            text.strip() for text in self.evidence_cache if isinstance(text, str) and text.strip()
        )[:600]
        explanation = self._text("degraded_reasoning", reason=reason, score=self.current_score)
        if evidence_preview:
            explanation += self._text("degraded_evidence", evidence=evidence_preview)
        if self.evidence_sources:
            locate = self._text("locate_sources", sources=", ".join(self.evidence_sources))
        else:
            locate = self._text("locate_none")
        return self._success_result(locate, list(self.evidence_cache), explanation, report_degraded=True)

    def _success_result(
        self,
        step1_locate: str,
        step2_evidence: List[str],
        step3_reasoning: Any,
        *,
        report_degraded: bool = False,
    ) -> Dict[str, Any]:
        """Successful item payload shared by the normal and the degraded report."""
        iteration_stats: Dict[str, Any] = {
            "total_chunks": len(self.evidence_sources) if self.evidence_sources else 0,
            "evidence_count": len(self.evidence_cache),
            "report_evidence_count": len(step2_evidence),
            "early_stopped": self.current_score == 7,
            "llm_call_counts": dict(self._llm_call_counts),
        }
        if report_degraded:
            iteration_stats["report_degraded"] = True
        return self._with_rule_engine_payload(sanitize_unicode({
            "status": "success",
            "skill_id": self.skill_id,
            "domain": self.domain_id,
            "title": self.skill_config.get("title", ""),
            "chain_of_thought": {
                "step1_locate": step1_locate,
                "step2_evidence": step2_evidence,
                "step3_reasoning": step3_reasoning,
                "score": self.current_score,
            },
            "evidence_sources": self.evidence_sources,
            "iteration_stats": iteration_stats,
        }))

    def _text(self, key: str, **values: Any) -> str:
        """Server-generated item text in the appraisal language."""
        lang = "zh" if str(self.lang or "").lower().startswith("zh") else "en"
        return _SERVER_TEXTS[lang][key].format(**values)

    def _no_evidence_result(self) -> Dict[str, Any]:
        """无证据时的结果"""
        return self._with_rule_engine_payload(sanitize_unicode({
            "status": "no_evidence",
            "skill_id": self.skill_id,
            "domain": self.domain_id,
            "title": self.skill_config.get("title", ""),
            "chain_of_thought": {
                "step1_locate": self._text("locate_none"),
                "step2_evidence": [],
                "step3_reasoning": self._text("no_evidence_reasoning"),
                "score": 1,
            },
            "evidence_sources": [],
            "iteration_stats": {
                "total_chunks": 0,
                "evidence_count": 0,
                "early_stopped": False,
            },
        }))
    
    def _error_result(self, error: str) -> Dict[str, Any]:
        """错误结果"""
        return self._with_rule_engine_payload(sanitize_unicode({
            "status": "error",
            "skill_id": self.skill_id,
            "error": error,
        }))


def run_iterative_evaluation(
    task_id: str,
    skill_id: str,
    lang: str = "en",
    cancellation_token: CancellationToken | None = None,
    analysis_engine: str | None = None,
) -> Dict[str, Any]:
    """
    执行迭代评价的快捷函数
    
    Args:
        task_id: 任务 ID
        skill_id: 条目 ID
        lang: 提示词语言
        analysis_engine: 本任务使用的评价引擎；为空时沿用全局配置
    
    Returns:
        评价结果
    """
    evaluator = IterativeEvaluator(
        task_id,
        skill_id,
        lang,
        cancellation_token=cancellation_token,
        analysis_engine=analysis_engine,
    )
    try:
        with bind_cancellation(cancellation_token):
            return evaluator.evaluate()
    except CancellationRequested as exc:
        return sanitize_unicode({
            "status": "cancelled",
            "skill_id": skill_id,
            "error": str(exc),
        })


